def main():
    meta = json.load(open(f"{D}/meta.json", encoding="utf-8"))
    unit = meta["chapters"][0].get("unit", "")
    keep = [c for c in meta["chapters"] if not c["id"].startswith("e")]
    meta["chapters"] = keep
    for cid, title, qs in NEW:
        rng = random.Random(cid); out = []
        for q, r, w1, w2, w3, why in qs:
            ch = [r, w1, w2, w3]; rng.shuffle(ch)
            out.append({"question": q, "choices": [f"{i+1}. {c}" for i, c in enumerate(ch)], "answer": str(ch.index(r) + 1), "why": why})
        json.dump(out, open(f"{D}/chapters/{cid}.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        meta["chapters"].append({"id": cid, "num": "", "title": title, "unit": unit})
    for i, c in enumerate(meta["chapters"]): c["num"] = str(i + 1)
    json.dump(meta, open(f"{D}/meta.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(sum(len(x[2]) for x in NEW), "νέες ερωτήσεις")
main()
