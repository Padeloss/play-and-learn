PATH = "Α΄ Γυμνασίου/Γεωλογία–Γεωγραφία"
OLD = {}
for cid in ["01", "02", "03", "04", "05"]:
    raw = subprocess.check_output(["git", "show", f"95b37a3:backend/lessons/{PATH}/chapters/{cid}.json"], text=True)
    for q in json.loads(raw):
        ch = [re.sub(r"^\d+\.\s*", "", c) for c in q["choices"]]
        right = ch[int(q["answer"]) - 1]
        OLD[q["question"]] = (q["question"], right, *[c for c in ch if c != right])

def old(prefix):
    hits = [v for k, v in OLD.items() if k.startswith(prefix)]
    assert len(hits) == 1, prefix
    return hits[0]

