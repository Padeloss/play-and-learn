OLD = {}
for cid in ["01", "02", "03", "04"]:
    rel = f"{ROOT}/{PATH}/chapters/{cid}.json"
    try:
        raw = subprocess.check_output(["git", "show", f"bc8abe1:{rel}"], text=True)
    except subprocess.CalledProcessError:
        continue
    for q in json.loads(raw):
        ch = [re.sub(r"^\d+\.\s*", "", c) for c in q["choices"]]
        right = ch[int(q["answer"]) - 1]
        OLD[q["question"]] = (q["question"], right, *[c for c in ch if c != right])

def old(prefix):
    hits = [v for k, v in OLD.items() if k.startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]

